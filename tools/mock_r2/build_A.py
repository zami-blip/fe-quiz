# ---------------------------------------------------------------- M2A05 BNF
def gen_expr(s):
    # <式> ::= <項> | <式> + <項> ; <項> ::= <因子> | <項> * <因子> ; <因子> ::= a | b | ( <式> )
    pos = 0

    def factor():
        nonlocal pos
        if pos < len(s) and s[pos] in "ab":
            pos += 1
            return True
        if pos < len(s) and s[pos] == "(":
            pos += 1
            if not expr():
                return False
            if pos < len(s) and s[pos] == ")":
                pos += 1
                return True
        return False

    def term():
        nonlocal pos
        if not factor():
            return False
        while pos < len(s) and s[pos] == "*":
            pos += 1
            if not factor():
                return False
        return True

    def expr():
        nonlocal pos
        if not term():
            return False
        while pos < len(s) and s[pos] == "+":
            pos += 1
            if not term():
                return False
        return True

    return expr() and pos == len(s)


