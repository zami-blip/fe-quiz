procs = [("P1", 0, 5, 3), ("P2", 1, 3, 1), ("P3", 2, 4, 2), ("P4", 4, 2, 1)]


def sched(preempt=True, by="pri"):
    rem = {p[0]: p[2] for p in procs}
    fin = {}
    t = 0
    cur = None
    while len(fin) < len(procs):
        ready = [p for p in procs if p[1] <= t and p[0] not in fin]
        if not ready:
            t += 1
            continue
        key = (lambda p: (p[3], p[1])) if by == "pri" else (lambda p: p[1])
        if cur is None or cur not in [r[0] for r in ready]:
            cur = min(ready, key=key)[0]
        elif preempt:
            best = min(ready, key=key)
            curp = [p for p in procs if p[0] == cur][0]
            if key(best) < key(curp) and best[3] < curp[3]:
                cur = best[0]
        rem[cur] -= 1
        t += 1
        if rem[cur] == 0:
            fin[cur] = t
            cur = None
    return fin


