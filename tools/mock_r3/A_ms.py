# ------------------------------------------------------------------ M3A44 山崩し
tasks = {"A": (2, 2, []), "B": (3, 3, ["A"]), "C": (2, 2, ["A"]), "D": (3, 1, []), "E": (2, 2, ["B", "C"])}
order = ["A", "B", "C", "D", "E"]
es = {}
for t in order:
    d, p, pre = tasks[t]
    es[t] = max([es[x] + tasks[x][0] for x in pre], default=0)
LEN = max(es[t] + tasks[t][0] for t in order)
lf = {}
for t in reversed(order):
    succ = [s_ for s_ in order if t in tasks[s_][2]]
    lf[t] = min([lf[s_] - tasks[s_][0] for s_ in succ], default=LEN)
ls = {t: lf[t] - tasks[t][0] for t in order}
assert LEN == 7 and es == {"A": 0, "B": 2, "C": 2, "D": 0, "E": 5} and ls == {"A": 0, "B": 2, "C": 3, "D": 4, "E": 5}


def peak(start):
    load = [0] * LEN
    for t in order:
        d, p, _ = tasks[t]
        for k in range(start[t], start[t] + d):
            load[k] += p
    return max(load), load


p_es, load_es = peak(es)
best = None
for combo in itertools.product(*[range(es[t], ls[t] + 1) for t in order]):
    st = dict(zip(order, combo))
    if all(st[t] >= max([st[x] + tasks[x][0] for x in tasks[t][2]], default=0) for t in order):
        pk, ld = peak(st)
        if best is None or pk < best[0]:
            best = (pk, st, ld)
total_pd = sum(d * p for d, p, _ in tasks.values())
assert p_es == 6 and best[0] == 5 and total_pd == 24 and math.ceil(total_pd / LEN) == 4 and max(p for _, p, _ in tasks.values()) == 3
