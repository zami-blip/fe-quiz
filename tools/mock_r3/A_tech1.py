# ------------------------------------------------------------------ M3A02 NAND 回路の働き
def nand(*xs):
    return 0 if all(xs) else 1


def circ(a, b_, c):
    return nand(nand(a, b_), nand(b_, c), nand(c, a))


rows = [(a, b_, c) for a in (0, 1) for b_ in (0, 1) for c in (0, 1)]
cands = {"ア": lambda a, b_, c: int(a and b_ and c), "イ": lambda a, b_, c: (a + b_ + c) % 2,
         "ウ": lambda a, b_, c: int(a + b_ + c >= 2), "エ": lambda a, b_, c: int(a or b_ or c)}
match = [k for k, f in cands.items() if all(f(*r) == circ(*r) for r in rows)]
assert match == ["ウ"], match
