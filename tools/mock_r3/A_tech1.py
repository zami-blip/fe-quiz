# ------------------------------------------------------------------ M3A15 FIFO のページフォールト(枠を増やすと増える例)
ref = [2, 3, 1, 4, 2, 3, 5, 2, 3, 1, 4, 5]


def fifo(refs, k):
    fr, f, rows = [], 0, []
    for p in refs:
        hit = p in fr
        if not hit:
            f += 1
            if len(fr) == k:
                fr.pop(0)
            fr.append(p)
        rows.append((p, list(fr), hit))
    return f, rows


def lru(refs, k):
    fr, f = [], 0
    for p in refs:
        if p in fr:
            fr.remove(p)
        else:
            f += 1
            if len(fr) == k:
                fr.pop(0)
        fr.append(p)
    return f


