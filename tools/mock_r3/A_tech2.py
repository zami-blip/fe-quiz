# ------------------------------------------------------------------ M3A23 関数従属と候補キー
ATTR = "ABCDE"
FD = [("A", "B"), ("B", "C"), ("AD", "E")]


def closure(xs):
    c = set(xs)
    ch_ = True
    while ch_:
        ch_ = False
        for l, r in FD:
            if set(l) <= c and not set(r) <= c:
                c |= set(r)
                ch_ = True
    return c


keys = [set(k) for n in range(1, 6) for k in itertools.combinations(ATTR, n) if closure(k) == set(ATTR)]
cand = [k for k in keys if not any(o < k for o in keys)]
assert cand == [{"A", "D"}], cand
opts = [{"A", "D"}, {"A"}, {"A", "B", "D"}, {"D", "E"}]
is_cand = [l for l, o in zip("アイウエ", opts) if o in cand]
assert is_cand == ["ア"] and closure("A") == {"A", "B", "C"} and closure("ABD") == set(ATTR) and closure("DE") == {"D", "E"}
